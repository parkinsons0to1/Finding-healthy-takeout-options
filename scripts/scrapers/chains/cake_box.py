"""Cake Box (cakebox.com) — per-100g Nutritics tables on product pages.

Discovery
---------
`chain_discovery.json`'s existing note for this chain is accurate as far as
it goes (the `/ingredients` page's "protein" hits are all ingredient-
declaration prose like "Milk Protein", not a nutrition table) but stopped one
step short: every individual slice/cupcake/cheesecake/treat product page
carries a real "Nutritional Information" tab, e.g.

    https://www.cakebox.com/speculoos-crunchy-slice

    <div class="nutritics-info-wraper"><table class="table-nutritics-info">
      <tr><th>Nutritionals</th><th>Value/100g</th><th>% RI</th></tr>
      <tr><td>Energy</td><td>428kcal</td><td>21</td></tr>
      ...
      <tr><td>Protein</td><td>4.6g</td><td>9</td></tr>

This is server-rendered (plain `requests.get` sees it, no JS needed) and
generated by "Nutritics" (a third-party nutrition-calc SaaS UK bakeries
commonly license), not a filename-guessable PDF. Verified on 9 products
across all 4 categories below, not just one.

Why this doesn't move the rankable count
------------------------------------------
Every table is **per 100g** with no stated portion/slice weight anywhere on
the site (checked: product description tab, FAQs page, category pages —
none give a gram weight per slice/cupcake). Per the project's per-100g
exclusion rule this alone would already keep these rows out of ranking. But
even a genuine portion weight wouldn't help: protein *share* of calories is
scale-invariant, and every product sampled sits at 3-9% protein-by-calories
(Speculoos Crunchy Slice 428kcal/4.6g=4.3%, Caramelicious 323kcal/4.1g=5.1%,
Naked Biscoff Bliss 379kcal/3.8g=4.0%, Eatin' Speculoos 335kcal/3.3g=3.9%,
Box of 4 Cookie Cups 435kcal/4.3g=4.0%) — nowhere near the ranking floor.
This is the same shape as Hotel Chocolat: nutrition genuinely exists, is
genuinely never going to be rankable, ingested anyway so `coverage.py`
reports the real reason instead of "no nutrition found".

Scope
-----
Only the 4 categories whose product pages render a Nutritics table were
crawled: Slices, Treats, Cupcakes, Cheesecakes (server-rendered product
grids at `/slices`, `/treats`, `/cupcakes`, `/cheesecakes`, paginated via
`?p=N`). Celebration Cakes / Wedding Cakes are whole made-to-order cakes —
checked a sample product page (`/pineapple-berry-round-cake`) and it has no
`table-nutritics-info` block at all, so that whole category tree is skipped
rather than crawled for nothing.
"""
from __future__ import annotations

import html
import re
from concurrent.futures import ThreadPoolExecutor

from ..base import item, session, to_float

CHAIN = "cake_box"
SOURCE = "Cake Box product pages (Nutritics nutrition table)"
BASE = "https://www.cakebox.com"

CATEGORIES = ["slices", "treats", "cupcakes", "cheesecakes"]
WORKERS = 10

_PRODUCT_LINK_RE = re.compile(
    r'<a href="(https://www\.cakebox\.com/[a-z0-9-]+)"\s*class="product photo product-item-photo"')
_TITLE_RE = re.compile(r"<title>([^<]+)</title>")
_ROW_RE = re.compile(r"<tr[^>]*>(.*?)</tr>", re.S)
_CELL_RE = re.compile(r"<t[dh][^>]*>(.*?)</t[dh]>", re.S)
_TAG_RE = re.compile(r"<[^>]+>")

#: Two table layouts are in use across the catalogue: one row labelled
#: "Energy" (kcal value) followed by an unlabelled kJ row, and one with
#: separate "Energy Kj" / "Energy Kcal" rows — map both spellings to kcal so
#: neither layout silently drops the row (this is what caused every
#: "Energy Kcal"-labelled product, e.g. Hazelnut Tiramisu Slice, to be
#: skipped as "no kcal" during development).
_FIELD_MAP = {
    "energy": "kcal",  # value carries "kcal" suffix, stripped in _num
    "energy kcal": "kcal",
    "carbohydrate": "carbs_g",
    "protein": "protein_g",
    "fat": "fat_g",
    "sugars": "sugar_g",
    "saturated fat": "sat_g",
    "sodium (na)": "sodium_mg",  # cell text is "NNNmg", e.g. "330.4mg"
}


def _get(url: str, timeout: int = 30) -> str | None:
    try:
        r = session().get(url, timeout=timeout)
        if r.status_code == 200 and r.text:
            return r.text
    except Exception:
        pass
    return None


def _category_urls(slug: str) -> list[str]:
    """Product page URLs for one category, following `?p=N` pagination."""
    urls: list[str] = []
    page = 1
    while True:
        u = f"{BASE}/{slug}" if page == 1 else f"{BASE}/{slug}?p={page}"
        html = _get(u)
        if not html:
            break
        found = _PRODUCT_LINK_RE.findall(html)
        if not found:
            break
        urls.extend(found)
        page += 1
        if page > 30:  # sanity cap, no category is this deep
            break
    return list(dict.fromkeys(urls))


def _num(cell: str) -> float | None:
    m = re.search(r"-?\d+\.?\d*", cell.replace(",", "."))
    return float(m.group(0)) if m else None


def _parse_product(url: str, category: str) -> dict | None:
    page_html = _get(url)
    if not page_html:
        return None
    i = page_html.find("table-nutritics-info")
    if i < 0:
        return None
    j = page_html.find("</table>", i)
    block = page_html[i:j + 9]

    vals: dict[str, float] = {}
    for row in _ROW_RE.findall(block):
        cells = [_TAG_RE.sub("", c).strip() for c in _CELL_RE.findall(row)]
        if len(cells) < 2 or not cells[0]:
            continue
        label = cells[0].strip().lower()
        field = _FIELD_MAP.get(label)
        if field:
            vals[field] = _num(cells[1])

    kcal, protein = vals.get("kcal"), vals.get("protein_g")
    if kcal is None or protein is None or kcal <= 0:
        return None
    if protein * 4 > kcal * 1.15:
        return None

    tm = _TITLE_RE.search(page_html)
    name = html.unescape(tm.group(1).strip()) if tm else url.rsplit("/", 1)[-1].replace("-", " ").title()

    return item(
        CHAIN, name, SOURCE, url,
        item_id=url.rsplit("/", 1)[-1], category=category, serving_desc="100g",
        kcal=kcal, protein_g=protein,
        carbs_g=vals.get("carbs_g"), fat_g=vals.get("fat_g"),
        # UK label convention: salt (g) = sodium (mg) / 1000 * 2.5.
        salt_g=(vals["sodium_mg"] / 1000 * 2.5) if vals.get("sodium_mg") else None,
    )


def fetch() -> list[dict]:
    entries: list[tuple[str, str]] = []
    seen_urls: set[str] = set()
    for slug in CATEGORIES:
        category = slug.title()
        for u in _category_urls(slug):
            if u not in seen_urls:
                seen_urls.add(u)
                entries.append((u, category))
    if not entries:
        return []

    with ThreadPoolExecutor(WORKERS) as pool:
        results = list(pool.map(lambda e: _parse_product(*e), entries))

    out: list[dict] = []
    seen_names: set[str] = set()
    for row in results:
        if row is None:
            continue
        key = str(row["name"]).lower()
        if key in seen_names:
            continue
        seen_names.add(key)
        out.append(row)
    return out
